    private void jBtnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnProcessActionPerformed
        // TODO add your handling code here:
      
        // Get customer name 
        String customerName = jTxtCustomer.getText(); 

        // Get selected product 
        String productName = jCmbProduct.getSelectedItem().toString(); 

        // Get product price 
        double price = Double.parseDouble(jTxtPrice.getText()); 

        // Create ProductCalculations object 
        ProductCalculations calc = new ProductCalculations(price); 

        // Calculate VAT, commission and total 
        double vat = calc.GetVat(); 
        double commission = calc.GetCommission(); 
        double total = calc.GetTotal(); 
        
        // Display the sales information 

        javax.swing.JOptionPane.showMessageDialog(this, 
            "Customer Name: " + customerName + 
            "\nProduct: " + productName + 
            "\nVAT: R " + vat + 
            "\nCOMMISSION: R " + commission + 
            "\nTOTAL: R " + total); 
 
    }//GEN-LAST:event_jBtnProcessActionPerformed

